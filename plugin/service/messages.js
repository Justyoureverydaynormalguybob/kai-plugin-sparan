const catalogs = { en, es, "pt-BR": ptBR, fr, de };

/** The messages for `language`, each key falling back to English. */
function messages(language) {
  const c = catalogs[language] || en;
  return new Proxy(c, { get: (t, k) => (k in t ? t[k] : en[k]) });
}

module.exports = { messages, catalogs };
